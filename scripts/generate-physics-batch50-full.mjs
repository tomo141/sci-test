function rotateToIndex(item, targetIndex) {
  const cur = item.correct_choice_index;
  if (cur === targetIndex) return item;
  const shift = (cur - targetIndex + 4) % 4;
  const rot = (arr) => [...arr.slice(shift), ...arr.slice(0, shift)];
  return {
    ...item,
    choices: rot(item.choices),
    distractor_rationales: rot(item.distractor_rationales),
    correct_choice_index: targetIndex
  };
}

