function balanceAnswerPosition(item, targetIndex) {
  const cur = item.correct_choice_index;
  if (cur === targetIndex) return item;
  const choices = [...item.choices];
  const rationales = [...item.distractor_rationales];
  const correctChoice = choices[cur];
  const correctRationale = rationales[cur];
  const otherChoices = choices.filter((_, i) => i !== cur);
  const otherRationales = rationales.filter((_, i) => i !== cur);
  const newChoices = [];
  const newRationales = [];
  let otherIdx = 0;
  for (let i = 0; i < 4; i++) {
    if (i === targetIndex) {
      newChoices.push(correctChoice);
      newRationales.push(correctRationale);
    } else {
      newChoices.push(otherChoices[otherIdx]);
      newRationales.push(otherRationales[otherIdx]);
      otherIdx++;
    }
  }
  return {
    ...item,
    choices: newChoices,
    distractor_rationales: newRationales,
    correct_choice_index: targetIndex,
  };
}

