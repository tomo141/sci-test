const map = new Map();
for (const [domain, subdomains] of Object.entries(subdomainsByDomain)) {
  for (const subdomain of subdomains) map.set(`${domain}\0${subdomain}`, subdomain);
}
for (const [domain, grouped] of Object.entries(groups)) {
  for (const [target, labels] of Object.entries(grouped)) {
    for (const label of labels) map.set(`${domain}\0${label}`, target);
  }
}

const fallback = Object.fromEntries(Object.entries(subdomainsByDomain).map(([domain, list]) => [domain, list[0]]));
const report = [];

for (const file of files) {
  let source = fs.readFileSync(file, "utf8");
  const remap = (match, prefix, domain, oldSubdomain) => {
    const target = map.get(`${domain}\0${oldSubdomain}`) || fallback[domain] || oldSubdomain;
    if (target !== oldSubdomain && !map.has(`${domain}\0${oldSubdomain}`)) {
      const id = source.slice(0, source.indexOf(match)).match(/id: "([^"]+)"/g)?.at(-1)?.match(/"([^"]+)"/)?.[1] || "(generated-spec)";
      report.push({ file: path.relative(root, file), id, domain, oldSubdomain, target });
    }
    return `${prefix}"${target}"`;
  };
  source = source.replace(/(domain: "([^"]+)", subdomain: )"([^"]+)"/g, remap);
  source = source.replace(/(domain: "([^"]+)",\s*\n\s*subdomain: )"([^"]+)"/g, remap);
  fs.writeFileSync(file, source);
}

const reportLines = [
  "# 小分野再割当レポート",
  "",
  `実行時にマッピング表外だったラベル: ${report.length}件`,
  "",
  "| file | problem id | domain | old subdomain | new subdomain |",
  "| --- | --- | --- | --- | --- |",
  ...report.map((row) => `| ${row.file} | ${row.id} | ${row.domain} | ${row.oldSubdomain} | ${row.target} |`)
];
fs.writeFileSync(path.join(root, "docs/subdomain-remap-report.md"), `${reportLines.join("\n")}\n`);

const sqlLines = [
  "-- Generated by scripts/remap-subdomains.mjs",
  "-- Apply after question bank tables are loaded if production rows still contain legacy labels.",
  ...[...map.entries()].map(([key, target]) => {
    const [domain, oldSubdomain] = key.split("\0");
    return `update public.questions set subdomain = '${target.replaceAll("'", "''")}' where domain = '${domain.replaceAll("'", "''")}' and subdomain = '${oldSubdomain.replaceAll("'", "''")}';`;
  })
];
fs.writeFileSync(path.join(root, "supabase/seed/generated/subdomain-remap.sql"), `${sqlLines.join("\n")}\n`);

